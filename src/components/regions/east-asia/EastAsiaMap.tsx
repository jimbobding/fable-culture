export default function EastAsiaMap() {
  const router = useRouter();
  const [hovered, setHovered] = useState<string | null>(null);

  const stroke = "#b44036";
  const fillHover = "rgba(180, 64, 54, 0.25)";

  return (
    <div className="space-y-6">
      <div className="relative overflow-hidden rounded-[2rem]">
        <img
          src="/images/continents/east-asia/map/east-asia-map.webp"
          alt="Map of East Asia"
          className="block h-auto w-full"
        />

        <svg
          className="absolute inset-0 h-full w-full"
          viewBox={`0 0 ${W} ${H}`}
          preserveAspectRatio="none"
        >
          {countries.map((country) => {
            const active = hovered === country.name;

            return (
              <polygon
                key={country.name}
                points={country.points}
                onMouseEnter={() => setHovered(country.name)}
                onMouseLeave={() => setHovered(null)}
                onClick={() => router.push(country.href)}
                style={{
                  fill: active ? fillHover : "transparent",
                  stroke: active ? stroke : "transparent",
                  strokeWidth: active ? 4 : 0,
                  cursor: "pointer",
                  transition: "fill 0.25s ease, stroke 0.25s ease",
                }}
              />
            );
          })}
        </svg>
      </div>

      <div className="border-l-2 border-[#b44036] bg-[#f3eddf] px-5 py-4">
        <p className="text-sm leading-relaxed text-[#34473d] sm:text-base">
          <span className="font-bold text-[#b44036]">Explore the map:</span>{" "}
          Hover or tap a country to begin exploring East Asia.
        </p>
      </div>

      {hovered && (
        <div className="text-center">
          <span className="inline-flex items-center rounded-full border border-[#d6b76f] bg-[#f3eddf] px-5 py-2 text-sm font-bold text-[#34473d] shadow-sm">
            {hovered}
          </span>
        </div>
      )}
    </div>
  );
}
